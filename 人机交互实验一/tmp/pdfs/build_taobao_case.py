        text(p,x+14,y+47,195,25,'候选商品 B · 500mL',11)
        box(p,x+79,y+84,65,95,PALE)
        box(p,x+97,y+96,28,70,(0.85,0.90,0.92))
        text(p,x+15,y+190,194,25,'¥79  /  商品信息示意',11,ORANGE)
