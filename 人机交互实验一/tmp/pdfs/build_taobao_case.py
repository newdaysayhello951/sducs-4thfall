def table(p,y,rows,widths):
    x0=40
    for i,row in enumerate(rows):
        h=43 if i==0 else 54
        x=x0
        for s,w in zip(row,widths):
            box(p,x,y,w,h,PALE if i==0 else ((0.97,0.98,0.99) if i%2 else (1,1,1)),(0.87,0.89,0.91))
            text(p,x+8,y+7,w-16,h-9,s,10)
            x+=w
        y+=h
    return y

