def box(p, x, y, w, h, fill=(0.96, 0.97, 0.98), border=None):
    p.draw_rect(fitz.Rect(x,y,x+w,y+h), color=border, fill=fill, width=0.7)

def text(p, x, y, w, h, s, size=11, color=INK):
    spare = p.insert_textbox(fitz.Rect(x,y,x+w,y+h), s, fontname='CN', fontsize=size, color=color, lineheight=1.55)
    if spare < 0:
        raise RuntimeError(f'Text overflow: {s[:45]} ({spare})')

def page(n, title, sub):
    p = doc.new_page(width=595, height=842)
    p.insert_font(fontname='CN', fontfile=FONT)
    box(p,0,0,595,9,ORANGE)
    text(p,40,27,515,20,'人机交互实验课作业 0  /  QUICK USABILITY TEST',9,GRAY)
